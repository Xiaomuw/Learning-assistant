def list_builtin_seed_subject_ids() -> list[str]:
    return [subject_id for subject_id in CANONICAL_SUBJECT_IDS if subject_id in BUILTIN_NOTEBOOK_SEED]


def get_builtin_seed_chapters(subject_id: str) -> list[BuiltinSeedChapter]:
    return list(BUILTIN_NOTEBOOK_SEED.get(subject_id, []))


def build_builtin_seed_payload(subject_id: str) -> tuple[list[str], list[dict[str, Any]]]:
    texts: list[str] = []
    metadatas: list[dict[str, Any]] = []
    for chapter in get_builtin_seed_chapters(subject_id):
        texts.append(f"{chapter.title}\n\n{chapter.content}")
        metadatas.append(
            {
                "subject_id": subject_id,
                "doc_type": "chapter",
                "source": "seed:built_in",
                "source_id": f"seed:{subject_id}:{chapter.chapter_key}",
                "knowledge_point": chapter.knowledge_point,
                "chapter": chapter.title,
            }
        )
    return texts, metadatas
